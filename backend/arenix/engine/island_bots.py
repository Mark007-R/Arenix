"""Rule-based contestants for impostor mode (no LLM).

Islanders do tasks (tower, beacons, shrine), report bodies they find and build suspicion only from
what they were allowed to observe: who they saw where (sightings), kills they witnessed, skill
clues, and other contestants' claims (weighted by how much they trust the speaker). Impostors fake
tasks, stalk isolated islanders, kill only when nobody else is close enough to witness it, then
walk away, lie about where they were and push the blame onto someone plausible.

Everything a bot says is generated by `talk.Talker` from that knowledge — never from hidden state.
Every action goes through the Match like a human's and can be refused.
"""

from __future__ import annotations

import math
import random
from collections import deque
from typing import TYPE_CHECKING, Any

from . import physics
from . import roles as R
from .bots import BotBrain, BotIntent, Goal
from .map import GameMap
from .pathfinding import path_to_point
from .talk import Talker, parse_claim, place

if TYPE_CHECKING:
    from .events import GameEvent
    from .match import Observation

SIGHTING_EVERY = 10  # ticks
SIGHTING_MEMORY = 90  # samples (~45 s)
MAX_MEETING_LINES = 3
MAX_REACTIONS = 2
MIN_LINE_GAP = 40  # ticks between two lines from the same bot
STALK_CLEARANCE = 10.0  # impostor bots only strike with no one else this close to the victim...
UNSEEN_RADIUS = 11.0  # ...and nobody close enough to see the impostor (the base view radius)
FIRST_IMPRESSION = 0.22  # islanders start with small random suspicions, so they can be wrong


class IslandBrain(BotBrain):
    def __init__(self, cid: str, game_map: GameMap, rng: random.Random) -> None:
        super().__init__(cid, game_map, rng)
        self.talker = Talker(rng)
        self.role = R.ISLANDER
        self.fellow: set[str] = set()
        self.skill: str | None = None
        self.aggression = rng.uniform(0.45, 0.9)
        self.sightings: dict[str, deque[tuple[int, float, float]]] = {}
        self.trail: deque[tuple[int, str]] = deque(maxlen=60)
        self.suspicion: dict[str, float] = {}
        self.cleared: set[str] = set()
        self.tasks_seen: dict[str, int] = {}
        self.known_impostors: set[str] = set()
        self.dead: set[str] = set()
        self.witnessed: list[tuple[str, str, str]] = []  # killer, victim, region
        self.clue: tuple[str, str] | None = None
        self.vision: str | None = None
        self.lookout_region: str | None = None
        self.attacked_by: str | None = None
        self.body: dict[str, Any] | None = None  # last reported body
        self.meeting_claims: list[tuple[str, dict[str, Any]]] = []
        self.talk_queue: list[tuple[int, int, str | None, str, dict[str, Any] | None]] = []
        self.last_said = -10_000
        self.lines_this_meeting = 0
        self.reactions_this_meeting = 0
        self.meeting = 0
        self.point_goal: tuple[str, str] | None = None  # ("report", victim) | ("hunt", target)
        self.point_replan_at = 0
        self.point_tile: tuple[int, int] | None = None
        self.faked: set[str] = set()
        self.beacon_errand = False  # fetching wood to light a beacon
        self.meeting_lie: str | None = None
        self.flee_until = 0
        self.next_hunt_check = 0
        self.next_sabotage_check = rng.randint(600, 1400)
        self.shot_impostor: str | None = None
        self.next_chatter = rng.randint(900, 2200)
        self.shield_at = rng.randint(600, 2400)

    # ------------------------------------------------------------- helpers
    def n(self, cid: str | None) -> str:
        return self.names.get(cid or "", cid or "someone")

    def sus(self, cid: str, delta: float) -> None:
        if cid == self.cid:
            return
        self.suspicion[cid] = max(-1.0, min(1.0, self.suspicion.get(cid, 0.0) + delta))

    def my_region(self, obs: Observation) -> str:
        return self.map.region_at(obs.x, obs.y) or "the wilds"

    def queue(self, obs: Observation, delay: int, intent: str, claim: dict[str, Any] | None = None, **kw: Any) -> None:
        """Queue a line. intent "vote_intent:dynamic" is rendered when it is due."""
        text = "" if intent.endswith(":dynamic") else self.talker.say(intent, **kw)
        meeting = self.meeting if obs.phase != "explore" else 0
        self.talk_queue.append((obs.tick + delay, meeting, intent if not text else None, text, claim))

    def is_islander(self) -> bool:
        """Islanders and the sheriff (the jester plays like a liar, the impostor like a hunter)."""
        return R.team(self.role) == R.ISLANDER

    # ------------------------------------------------------------- perception
    def _observe(self, obs: Observation) -> None:
        self.role = obs.role
        self.fellow = set(obs.fellow_impostors)
        self.skill = obs.skill
        if not self.suspicion and obs.alive_ids:
            for cid in sorted(obs.alive_ids):
                if cid != self.cid:
                    self.suspicion[cid] = round(self.rng.uniform(0.0, FIRST_IMPRESSION), 3)
        if obs.tick % SIGHTING_EVERY == 0:
            for cid, (x, y) in obs.visible_positions.items():
                self.sightings.setdefault(cid, deque(maxlen=SIGHTING_MEMORY)).append((obs.tick, x, y))
            self.trail.append((obs.tick, self.my_region(obs)))

    def seen_near(self, cid: str, x: float, y: float, since: int, radius: float) -> float | None:
        best: float | None = None
        for t, sx, sy in self.sightings.get(cid, ()):
            if t >= since:
                d = math.hypot(sx - x, sy - y)
                if d <= radius and (best is None or d < best):
                    best = d
        return best

    def companions(self, obs: Observation, window: int = 400) -> list[str]:
        out = []
        for cid, samples in self.sightings.items():
            if cid in self.dead or cid in self.fellow:
                continue
            close = [s for s in samples if obs.tick - s[0] <= window and math.hypot(s[1] - obs.x, s[2] - obs.y) <= 6]
            if len(close) >= 4:
                out.append(cid)
        return out

    def recent_region(self, obs: Observation) -> str:
        regions = [r for t, r in self.trail if obs.tick - t <= 900]
        if not regions:
            return self.my_region(obs)
        return max(dict.fromkeys(regions), key=regions.count)

    # ------------------------------------------------------------- events
    def _learn_event(self, obs: Observation, ev: GameEvent) -> None:  # noqa: C901 — one branch per event type
        d = ev.data
        me = self.cid
        t = ev.type
        if t == "kill_witnessed" and d.get("cause", "impostor") != "impostor":
            # A sheriff's shot: a hit proves the shooter innocent (the victim was an impostor).
            self.dead.add(d["victim"])
            if d.get("cause") == "sheriff":
                self.cleared.add(d["killer"])
                self.sus(d["killer"], -1.0)
        elif t == "kill_witnessed":
            killer, victim = d["killer"], d["victim"]
            self.known_impostors.add(killer)
            self.suspicion[killer] = 1.0
            self.dead.add(victim)
            self.witnessed.append((killer, victim, d["region"]))
            if self.communicate and obs.phase == "explore":
                self.queue(
                    obs,
                    self.rng.randint(4, 14),
                    "saw_kill_explore",
                    {"type": "accuse", "target": killer, "about": "saw"},
                    target=self.n(killer),
                    victim=self.n(victim),
                    region=d["region"],
                )
        elif t == "contestant_killed":
            self.dead.add(d["victim"])
            if d.get("cause") == "sheriff" and d["killer"] == me:
                self.shot_impostor = d["victim"]
        elif t == "ally_lost":
            self.dead.add(d["ally"])
        elif t == "lookout_alert":
            self.lookout_region = d["region"]
        elif t == "shield_blocked":
            if me in (d["target"], d["medic"]):
                self.known_impostors.add(d["attacker"])
                self.suspicion[d["attacker"]] = 1.0
                if d["target"] == me:
                    self.attacked_by = d["attacker"]
        elif t == "shrine_vision":
            self.vision = d["innocent"]
            self.cleared.add(d["innocent"])
            self.suspicion[d["innocent"]] = -1.0
        elif t in ("resources_delivered", "beacon_lit") and d["contestant"] != me:
            # Seeing someone actually complete a task is proof: impostors can only pretend.
            accepted = d.get("accepted")
            if t == "beacon_lit" or (accepted and sum(accepted.values()) > 0):
                who = d["contestant"]
                self.tasks_seen[who] = self.tasks_seen.get(who, 0) + 1
                self.sus(who, -0.3)
                if self.tasks_seen[who] >= 2:
                    self.cleared.add(who)
        elif t == "detective_clue":
            a, b = d["suspects"]
            self.clue = (a, b)
            for x in (a, b):
                if x not in self.cleared:
                    self.sus(x, 0.45)
        elif t == "deaths_revealed":
            self.dead.update(d["dead"])
        elif t == "meeting_called":
            self._on_meeting(obs, d)
        elif t == "vote_resolved":
            self._on_vote_result(obs, d)
        elif t == "chat" and d["sender"] != me:
            self._on_chat(obs, d)

    def _on_meeting(self, obs: Observation, d: dict[str, Any]) -> None:
        self.meeting = int(d["meeting"])
        self.meeting_claims = []
        self.meeting_lie = None
        self.next_chatter = max(self.next_chatter, obs.tick + 900 + self.rng.randint(300, 1500))
        self.lines_this_meeting = 0
        self.reactions_this_meeting = 0
        self.talk_queue = [q for q in self.talk_queue if q[1] == 0 and q[0] > obs.tick - 100]
        self.point_goal = None
        self.body = None
        if d["cause"] == "body":
            self.body = {"victim": d["victim"], "region": d["region"], "x": d["x"], "y": d["y"], "caller": d["caller"]}
            self.dead.add(d["victim"])
            if self.is_islander():
                self._suspect_from_sightings(obs, d["x"], d["y"], exclude=d["caller"])
        if self.communicate:
            self._plan_meeting(obs, d)

    def _suspect_from_sightings(self, obs: Observation, bx: float, by: float, exclude: str | None = None) -> None:
        since = obs.tick - 700
        with_me = set(self.companions(obs, 300))
        far_from_me = math.hypot(obs.x - bx, obs.y - by) > 15
        for cid in list(self.sightings):
            if cid in self.dead or cid in self.cleared or cid == exclude:
                continue  # the reporter is near the body because they found it
            near = self.seen_near(cid, bx, by, since, 7.5)
            if near is not None:
                self.sus(cid, 0.08 + 0.2 * (1 - near / 10))
            elif cid in with_me and far_from_me:
                self.sus(cid, -0.25)

    def _on_vote_result(self, obs: Observation, d: dict[str, Any]) -> None:
        out = d.get("eliminated")
        if out is None:
            return
        self.dead.add(out)
        if d.get("was_impostor") is True:
            self.known_impostors.discard(out)
            for voter, target in d["votes"].items():
                if target == out:
                    self.sus(voter, -0.2)
            if self.is_islander() and self.communicate and self.rng.random() < 0.35:
                self.queue(obs, self.rng.randint(5, 40), "ejected_good")
        elif d.get("was_impostor") is False:
            self.cleared.add(out)
            for voter, target in d["votes"].items():
                if target == out and voter != self.cid:
                    self.sus(voter, 0.12)
            if self.is_islander() and self.communicate and self.rng.random() < 0.35:
                self.queue(obs, self.rng.randint(5, 40), "ejected_bad")

    def _credibility(self, sender: str) -> float:
        return max(0.0, min(1.0, 0.5 + 0.5 * self.beliefs.trust.get(sender, 0.0) - self.suspicion.get(sender, 0.0)))

    def _on_chat(self, obs: Observation, d: dict[str, Any]) -> None:
        sender = d["sender"]
        if d.get("ghost"):
            return
        claim = d.get("claim") or parse_claim(d["text"], self.names, sender)
        if not claim or claim.get("type") == "skip":
            return
        target = claim.get("target")
        kind = claim["type"]
        if obs.phase != "explore":
            self.meeting_claims.append((sender, claim))
        cred = self._credibility(sender)
        me = self.cid
        if kind == "accuse" and target is not None:
            about = claim.get("about")
            # Evidence ("I saw it") counts far more than agreeing with someone or announcing a vote.
            weight = {"saw": 0.35, "agree": 0.05, "vote": 0.04, "counter": 0.05}.get(str(about), 0.15)
            if target == me:
                if self.is_islander():
                    # I know I'm innocent: whoever accuses me is wrong — or lying.
                    self.sus(sender, 0.6 if about == "saw" else 0.25 if about is None else 0.08)
                if about != "vote":
                    self._react_accused(obs, sender, claim)
            else:
                if self.is_islander() and target not in self.cleared:
                    self.sus(target, weight * cred)
                if about is None or about == "saw":
                    self._react_to_accusation(obs, sender, target)
        elif kind == "clear" and target is not None and target != me:
            if self.is_islander():
                self.sus(target, -0.12 * cred)
        elif kind == "clue":
            for x in (target, claim.get("about")):
                if x and x != me and self.is_islander() and x not in self.cleared:
                    self.sus(x, 0.25 * cred)
            if me in (target, claim.get("about")):
                self._react_accused(obs, sender, claim)
        elif kind == "ask" and target == me:
            self._answer_where(obs)
        elif kind == "mention" and target == me and obs.phase == "explore" and self.rng.random() < 0.5:
            self.queue(obs, self.rng.randint(20, 50), "greet", target=self.n(sender))

    def _react_accused(self, obs: Observation, accuser: str, claim: dict[str, Any]) -> None:
        if not self.communicate or self.reactions_this_meeting >= MAX_REACTIONS:
            return
        self.reactions_this_meeting += 1
        region = self.recent_region(obs) if self.is_islander() else self._lie_region(obs)
        self.queue(obs, self.rng.randint(20, 60), "defend", {"type": "clear", "target": self.cid}, region=region)
        # "No, YOU are sus" is weak evidence; islanders only push back hard when they have a reason.
        strong = claim.get("about") == "saw" or self.suspicion.get(accuser, 0) > 0.5
        if (strong or not self.is_islander()) and self.rng.random() < 0.6:
            self.queue(
                obs,
                self.rng.randint(60, 120),
                "counter",
                {"type": "accuse", "target": accuser, "about": "counter"},
                target=self.n(accuser),
            )

    def _react_to_accusation(self, obs: Observation, accuser: str, target: str) -> None:
        if not self.communicate or obs.phase == "explore" or self.reactions_this_meeting >= MAX_REACTIONS:
            return
        if self.rng.random() > self.personality.chatty + 0.3:
            return
        if self.is_islander():
            s = self.suspicion.get(target, 0.0)
            if target in self.cleared or (target in self.companions(obs, 900) and s < 0.2):
                self.reactions_this_meeting += 1
                self.queue(
                    obs, self.rng.randint(30, 90), "doubt", {"type": "clear", "target": target}, target=self.n(target)
                )
            elif s > 0.25:
                self.reactions_this_meeting += 1
                self.queue(
                    obs,
                    self.rng.randint(40, 160),
                    "agree",
                    {"type": "accuse", "target": target, "about": "agree"},
                    target=self.n(target),
                )
        elif target in self.fellow:
            if self.rng.random() < 0.5:
                self.reactions_this_meeting += 1
                self.queue(
                    obs, self.rng.randint(30, 90), "doubt", {"type": "clear", "target": target}, target=self.n(target)
                )
        elif target != self.cid and self.rng.random() < 0.6:
            self.reactions_this_meeting += 1
            self.queue(
                obs,
                self.rng.randint(40, 160),
                "agree",
                {"type": "accuse", "target": target, "about": "agree"},
                target=self.n(target),
            )

    def _answer_where(self, obs: Observation) -> None:
        if not self.communicate or self.reactions_this_meeting >= MAX_REACTIONS + 1:
            return
        self.reactions_this_meeting += 1
        region = self.recent_region(obs) if self.is_islander() else self._lie_region(obs)
        self.queue(obs, self.rng.randint(20, 50), "answer_where", region=region)

    def _lie_region(self, obs: Observation) -> str:
        """Somewhere plausible that is far from the body (impostors only)."""
        if self.meeting_lie is not None:
            return self.meeting_lie
        honest = self.recent_region(obs)
        if self.body is None or honest != self.body["region"]:
            self.meeting_lie = honest
        else:
            options = [r.name for r in self.map.regions[:13] if r.name not in (self.body["region"], "Village")]
            self.meeting_lie = self.rng.choice(options) if options else honest
        return self.meeting_lie

    # ------------------------------------------------------------- meeting talk
    def _plan_meeting(self, obs: Observation, d: dict[str, Any]) -> None:
        delay = self.rng.randint(40, 120)

        def step() -> int:
            nonlocal delay
            delay += self.rng.randint(120, 260)
            return delay

        if d.get("caller") == self.cid:
            if d["cause"] == "body":
                self.queue(
                    obs,
                    self.rng.randint(10, 25),
                    "found_body",
                    {"type": "report"},
                    victim=self.n(d["victim"]),
                    region=d["region"],
                )
            elif d["cause"] == "bell":
                self.queue(obs, self.rng.randint(10, 25), "bell")
        if self.is_islander():
            self._plan_islander(obs, step)
        elif self.role == R.JESTER:
            self._plan_jester(obs, step)
        else:
            self._plan_impostor(obs, step)
        # Announce a vote near the end of the discussion, decided when it is due.
        self.queue(obs, self.rng.randint(620, 860), "vote_intent:dynamic")

    def _plan_islander(self, obs: Observation, step: Any) -> None:
        said = False
        if self.shot_impostor:
            self.queue(
                obs, step(), "sheriff_reveal", {"type": "clear", "target": self.cid}, target=self.n(self.shot_impostor)
            )
            self.shot_impostor = None
            said = True
        for killer, victim, region in self.witnessed:
            if killer not in self.dead:
                self.queue(
                    obs,
                    step(),
                    "saw_kill",
                    {"type": "accuse", "target": killer, "about": "saw"},
                    target=self.n(killer),
                    victim=self.n(victim),
                    region=region,
                )
                said = True
        self.witnessed = []
        if self.attacked_by and self.attacked_by not in self.dead:
            self.queue(
                obs,
                step(),
                "shielded",
                {"type": "accuse", "target": self.attacked_by, "about": "saw"},
                target=self.n(self.attacked_by),
            )
            self.attacked_by = None
            said = True
        if self.clue:
            a, b = self.clue
            self.queue(obs, step(), "detective", {"type": "clue", "target": a, "about": b}, a=self.n(a), b=self.n(b))
            self.clue = None
            said = True
        if self.lookout_region:
            self.queue(
                obs, step(), "lookout", {"type": "info", "region": self.lookout_region}, region=self.lookout_region
            )
            self.lookout_region = None
        if self.vision and self.vision not in self.dead:
            self.queue(obs, step(), "vision", {"type": "clear", "target": self.vision}, target=self.n(self.vision))
            self.vision = None
        suspect = self._top_suspect(obs)
        if suspect is not None and self.suspicion.get(suspect, 0) > 0.3 and not said:
            if self.body and self.seen_near(suspect, self.body["x"], self.body["y"], obs.tick - 900, 9.0) is not None:
                self.queue(
                    obs,
                    step(),
                    "suspect_near",
                    {"type": "accuse", "target": suspect},
                    target=self.n(suspect),
                    region=self.body["region"],
                )
            else:
                self.queue(obs, step(), "suspect_vague", {"type": "accuse", "target": suspect}, target=self.n(suspect))
            said = True
        if self.rng.random() < 0.55 + self.personality.chatty * 0.5:
            mates = [c for c in self.companions(obs, 600) if c not in self.dead]
            if mates and self.rng.random() < 0.6:
                self.queue(
                    obs,
                    step(),
                    "alibi_with",
                    {"type": "clear", "target": mates[0]},
                    region=self.recent_region(obs),
                    other=self.n(mates[0]),
                )
            elif sum(obs.carrying.values()) or self.rng.random() < 0.4:
                self.queue(obs, step(), "alibi_task", task=self._task_phrase(obs))
            else:
                self.queue(obs, step(), "alibi", region=self.recent_region(obs))
            said = True
        if not said and self.rng.random() < 0.5:
            self.queue(obs, step(), "no_info")

    def _sheriff(self, obs: Observation) -> tuple[Any, ...] | None:
        """Chase a contestant this sheriff knows is an impostor (saw a kill, was attacked) and shoot."""
        known = [k for k in self.known_impostors if k in obs.visible_positions and k not in self.dead]
        if not known:
            return None
        target = known[0]
        tx, ty = obs.visible_positions[target]
        if math.hypot(tx - obs.x, ty - obs.y) <= R.SHERIFF_RANGE - 0.2:
            self._record(obs, f"shot {target} (known impostor)")
            self.point_goal = None
            return ("shoot", target)
        self.point_goal = ("hunt", target)
        return None

    def _sabotage(self, obs: Observation) -> tuple[Any, ...] | None:
        if not obs.sabotage_ready or obs.tick < self.next_sabotage_check:
            return None
        self.next_sabotage_check = obs.tick + self.rng.randint(200, 500)
        if self.rng.random() > 0.5:
            return None
        lit = sum(obs.beacons.values())
        kind = "douse" if lit >= 2 and self.rng.random() < 0.6 else "fog"
        self._record(obs, f"sabotage: {kind}")
        return ("sabotage", kind)

    def _plan_jester(self, obs: Observation, step: Any) -> None:
        """The jester wants to be voted out: vague, cagey and just suspicious enough."""
        if self.rng.random() < 0.35:
            self.queue(obs, step(), "jester_tease")
        elif self.rng.random() < 0.6:
            self.queue(obs, step(), "alibi", region=self.recent_region(obs))
        if self.rng.random() < 0.3:
            goat = self._scapegoat(obs)
            if goat is not None:
                self.queue(obs, step(), "suspect_vague", {"type": "accuse", "target": goat}, target=self.n(goat))

    def _plan_impostor(self, obs: Observation, step: Any) -> None:
        if self.rng.random() < 0.75:
            self.queue(obs, step(), "alibi", region=self._lie_region(obs))
        goat = self._scapegoat(obs)
        if goat is not None and self.rng.random() < 0.35:
            if self.body and self.seen_near(goat, self.body["x"], self.body["y"], obs.tick - 900, 12.0) is not None:
                self.queue(
                    obs,
                    step(),
                    "suspect_near",
                    {"type": "accuse", "target": goat},
                    target=self.n(goat),
                    region=self.body["region"],
                )
            else:
                self.queue(obs, step(), "suspect_vague", {"type": "accuse", "target": goat}, target=self.n(goat))

    def _task_phrase(self, obs: Observation) -> str:
        g = self.goal
        if g is not None and g.kind == "beacon":
            return f"heading to the beacon at {place(self._region_of(g.target_id))}"
        if g is not None and g.kind == "gather":
            resource = self.map.objects_by_id[g.target_id].props["resource"]
            return f"gathering {resource} in {place(self._region_of(g.target_id))}"
        return f"hauling materials to the Watchtower from {place(self.recent_region(obs))}"

    def _region_of(self, obj_id: str) -> str:
        o = self.map.objects_by_id[obj_id]
        return self.map.region_at(o.x + 0.5, o.y + 0.5) or "the wilds"

    def _alive_others(self, obs: Observation) -> list[str]:
        return [c for c in obs.alive_ids if c != self.cid and c not in self.dead]

    def _top_suspect(self, obs: Observation) -> str | None:
        cands = [c for c in self._alive_others(obs) if c not in self.cleared]
        if not cands:
            return None
        known = [c for c in cands if c in self.known_impostors]
        if known:
            return known[0]
        return max(cands, key=lambda c: (self.suspicion.get(c, 0.0), self.rng.random()))

    def _scapegoat(self, obs: Observation) -> str | None:
        cands = [c for c in self._alive_others(obs) if c not in self.fellow]
        if not cands:
            return None
        if self.body:
            near = [
                c for c in cands if self.seen_near(c, self.body["x"], self.body["y"], obs.tick - 900, 12.0) is not None
            ]
            if near:
                return self.rng.choice(near)
        accused = self._accusation_tally(cands)
        if accused:
            return max(accused, key=lambda c: (accused[c], c))
        return self.rng.choice(cands)

    def _accusation_tally(self, cands: list[str]) -> dict[str, int]:
        tally: dict[str, int] = {}
        for _, claim in self.meeting_claims:
            if claim.get("type") == "accuse" and claim.get("target") in cands:
                tally[claim["target"]] = tally.get(claim["target"], 0) + 1
        return tally

    # ------------------------------------------------------------- votes
    def _choose_vote(self, obs: Observation, others: list[str]) -> str | None:
        cands = [c for c in others if c not in self.dead and c != self.cid]
        if not self.is_islander():
            pool = [c for c in cands if c not in self.fellow]
            tally = self._accusation_tally(pool)
            if tally:
                target = max(tally, key=lambda c: (tally[c], c))
                self._record(obs, f"voted with the crowd against {target}")
                return target
            goat = self._scapegoat(obs) if self.rng.random() < 0.45 else None
            self._record(obs, f"voted {goat}" if goat else "skipped vote")
            return goat
        pool = [c for c in cands if c not in self.cleared]
        known = [c for c in pool if c in self.known_impostors]
        if known:
            self._record(obs, f"voted for {known[0]} (saw them kill)")
            return known[0]
        if not pool:
            return None
        best = max(pool, key=lambda c: (self.suspicion.get(c, 0.0), self.rng.random()))
        s = self.suspicion.get(best, 0.0)
        if s >= 0.5 or (s >= 0.3 and self.rng.random() < self.personality.decisive):
            self._record(obs, f"voted for {best}", suspicion=round(s, 2))
            return best
        self._record(obs, "skipped vote (not enough evidence)", suspicion=round(s, 2))
        return None

    def _vote_line(self, obs: Observation) -> tuple[str, dict[str, Any] | None]:
        others = self._alive_others(obs)
        state, n_records = self.rng.getstate(), len(self.decisions)
        target = self._choose_vote(obs, others)  # a preview: the real vote is decided again later
        self.rng.setstate(state)
        del self.decisions[n_records:]
        if target is None:
            return self.talker.say("skip_intent"), {"type": "skip"}
        claim = {"type": "accuse", "target": target, "about": "vote"}
        return self.talker.say("vote_intent", target=self.n(target)), claim

    # ------------------------------------------------------------- social loop
    def _social_island(self, obs: Observation) -> list[tuple[Any, ...]]:
        actions: list[tuple[Any, ...]] = []
        for proposer in obs.incoming_proposals:
            due = self.answer_at.setdefault(proposer, obs.tick + self.rng.randint(*self.personality.reaction) * 2)
            if obs.tick >= due:
                ok_ally = proposer in self.fellow or (
                    self.suspicion.get(proposer, 0.0) < 0.2 and self.rng.random() < self.personality.agreeable
                )
                actions.append(("respond", proposer, obs.ally is None and ok_ally))
                self.answer_at.pop(proposer, None)
        if obs.ally is not None and self.suspicion.get(obs.ally, 0.0) > 0.6:
            actions.append(("break",))
        if obs.phase == "vote" and not obs.has_voted:
            if self.vote_at is None:
                self.vote_at = obs.tick + self.rng.randint(40, min(300, max(41, obs.phase_ticks_left - 20)))
            if obs.tick >= self.vote_at:
                actions.append(("vote", self._choose_vote(obs, self._alive_others(obs))))
                self.vote_at = None
        elif obs.phase != "vote":
            self.vote_at = None
        if self.skill == "medic" and not obs.ability_used and obs.phase == "explore" and obs.tick >= self.shield_at:
            target = self._shield_target(obs)
            if target is not None:
                actions.append(("ability", target))
                self.shield_at = 1 << 30
        if self.role == R.IMPOSTOR and obs.phase == "explore":
            sab = self._sabotage(obs)
            if sab is not None:
                actions.append(sab)
        if self.communicate:
            self._explore_chatter(obs)
            line = self._next_line(obs)
            if line is not None:
                actions.append(line)
        return actions

    def _shield_target(self, obs: Observation) -> str | None:
        cands = self._alive_others(obs)
        if not self.is_islander():
            mates = [c for c in cands if c in self.fellow]
            return mates[0] if mates else None
        cands = [c for c in cands if c not in self.known_impostors]
        if not cands:
            return None
        return min(cands, key=lambda c: (self.suspicion.get(c, 0.0), self.rng.random()))

    def _explore_chatter(self, obs: Observation) -> None:
        if obs.phase != "explore" or obs.tick < self.next_chatter:
            return
        self.next_chatter = obs.tick + self.rng.randint(1300, 3000)
        if self.rng.random() > self.personality.chatty + 0.2:
            return
        g = self.goal
        if g is not None and g.kind == "gather":
            res = self.map.objects_by_id[g.target_id].props["resource"]
            self.queue(obs, 5, "explore_gather", resource=res, region=self._region_of(g.target_id))
        elif g is not None and g.kind == "beacon":
            self.queue(obs, 5, "explore_beacon", region=self._region_of(g.target_id))
        else:
            self.queue(obs, 5, "explore_misc")

    def _next_line(self, obs: Observation) -> tuple[Any, ...] | None:
        if obs.tick - self.last_said < MIN_LINE_GAP:
            return None
        # Meeting lines expire when the meeting ends; explore lines when a meeting starts.
        live = []
        for item in self.talk_queue:
            due, meeting, _, _, _ = item
            if (meeting and (obs.phase == "explore" or meeting != self.meeting)) or (
                not meeting and obs.phase != "explore" and due < obs.tick - 200
            ):
                continue
            live.append(item)
        self.talk_queue = live
        ready = [q for q in self.talk_queue if q[0] <= obs.tick]
        if not ready:
            return None
        item = min(ready, key=lambda q: q[0])
        self.talk_queue.remove(item)
        _, meeting, dynamic, text, claim = item
        if meeting:
            if self.lines_this_meeting >= MAX_MEETING_LINES + min(1, self.reactions_this_meeting):
                return None
            self.lines_this_meeting += 1
        if dynamic:
            if obs.phase not in ("discuss", "vote"):
                return None
            text, claim = self._vote_line(obs)
        self.last_said = obs.tick
        return ("say", text, claim)

    # ------------------------------------------------------------- impostor hunting
    def _safe_to_kill(self, obs: Observation, target: str) -> bool:
        """Nobody but the victim close enough to witness the kill — or to remember seeing me nearby."""
        tx, ty = obs.visible_positions[target]
        for cid, (x, y) in obs.visible_positions.items():
            if cid in (target, self.cid) or cid in self.fellow or cid in self.dead:
                continue
            if math.hypot(x - tx, y - ty) <= STALK_CLEARANCE or math.hypot(x - obs.x, y - obs.y) <= UNSEEN_RADIUS:
                return False
        return True

    def _pick_victim(self, obs: Observation) -> str | None:
        options = []
        for cid, (x, y) in obs.visible_positions.items():
            if cid in self.fellow or cid in self.dead or cid not in obs.alive_ids:
                continue
            d = math.hypot(x - obs.x, y - obs.y)
            if d <= 11 and self._safe_to_kill(obs, cid):
                options.append((d - 4 * self.suspicion.get(cid, 0.0), cid))
        return min(options)[1] if options else None

    def _hunt(self, obs: Observation) -> tuple[Any, ...] | None:
        """Kill if the current target is in range and unwatched; manage the hunt goal."""
        if self.point_goal and self.point_goal[0] == "hunt":
            target = self.point_goal[1]
            if not obs.kill_ready or target not in obs.visible_positions or not self._safe_to_kill(obs, target):
                self.point_goal = None
                return None
            tx, ty = obs.visible_positions[target]
            if math.hypot(tx - obs.x, ty - obs.y) <= R.KILL_RANGE - 0.15:
                self.point_goal = None
                self.goal = None
                self.path = []
                self.flee_until = obs.tick + 240
                self._record(obs, f"killed {target}")
                return ("kill", target)
            return None
        if obs.kill_ready and obs.tick >= self.next_hunt_check and obs.tick >= self.flee_until:
            self.next_hunt_check = obs.tick + 20
            if self.rng.random() < self.aggression:
                victim = self._pick_victim(obs)
                if victim is not None:
                    self.point_goal = ("hunt", victim)
                    self.point_tile = None
                    self.goal = None
                    self.awaiting_result = False
                    self._record(obs, f"stalking {victim}")
        return None

    # ------------------------------------------------------------- goals
    def choose_goal(self, obs: Observation) -> Goal | None:
        unlit = [b for b, lit in obs.beacons.items() if not lit and b not in self.faked]
        fleeing = obs.tick < self.flee_until
        if not unlit:
            self.beacon_errand = False
        elif not self.beacon_errand and (self.rng.random() < 0.3 or obs.mission_status != "active"):
            self.beacon_errand = True
        if self.beacon_errand and unlit:
            # A beacon burns one wood (impostors only pretend, so they can skip the wood).
            if obs.carrying.get("wood", 0) > 0 or not self.is_islander():
                beacon = min(
                    unlit, key=lambda b: self.map.objects_by_id[b].distance_to(obs.x, obs.y) + self.rng.random() * 20
                )
                return Goal("beacon", beacon)
            woods = [n for n, ch in obs.node_charges.items() if ch > 0 and n.startswith("wood")]
            if woods:
                return Goal("gather", min(woods, key=lambda n: self.map.objects_by_id[n].distance_to(obs.x, obs.y)))
        goal = super().choose_goal(obs)
        if fleeing and goal is not None and goal.kind == "gather":
            # Walk away from the scene: pick a node far from here.
            far = [
                nid
                for nid, ch in obs.node_charges.items()
                if ch > 0 and self.map.objects_by_id[nid].distance_to(obs.x, obs.y) > 18
            ]
            if far:
                return Goal("gather", self.rng.choice(far))
        return goal

    def _go_point(self, obs: Observation, x: float, y: float) -> BotIntent:
        tile = (math.floor(x), math.floor(y))
        if self.point_tile != tile or obs.tick >= self.point_replan_at or self.path_index >= len(self.path):
            path = path_to_point(self.map, (math.floor(obs.x), math.floor(obs.y)), tile)
            if path is None:
                self.point_goal = None
                return BotIntent()
            self.path, self.path_index, self.point_tile = path, 0, tile
            self.point_replan_at = obs.tick + 15
        while self.path_index < len(self.path):
            px, py = self.path[self.path_index]
            wx, wy = px + 0.5, py + 0.5
            ddx, ddy = wx - obs.x, wy - obs.y
            dist = math.sqrt(ddx * ddx + ddy * ddy)
            if dist <= 0.12:
                self.path_index += 1
                continue
            step_len = physics.SPEED * physics.DT * obs.speed
            scale = 1.0 / dist if dist > step_len else 1.0 / step_len
            return BotIntent(ddx * scale, ddy * scale)
        # Last waypoint reached: close the remaining gap directly.
        ddx, ddy = x - obs.x, y - obs.y
        dist = math.hypot(ddx, ddy) or 1.0
        return BotIntent(ddx / dist, ddy / dist)

    def _navigate_island(self, obs: Observation) -> BotIntent:
        # Islanders drop everything to report a body they can see.
        if self.is_islander() and obs.visible_bodies and not (self.point_goal and self.point_goal[0] == "report"):
            victim = min(obs.visible_bodies, key=lambda v: math.dist(obs.visible_bodies[v], (obs.x, obs.y)))
            self.point_goal = ("report", victim)
            self.point_tile = None
            self.goal = None
            self.awaiting_result = False
            self._record(obs, f"found {victim}'s body; going to report it")
        if self.point_goal is not None:
            kind, who = self.point_goal
            if kind == "report":
                pos = obs.visible_bodies.get(who)
                if pos is None:
                    self.point_goal = None
                    return BotIntent()
                if math.dist(pos, (obs.x, obs.y)) <= R.REPORT_RANGE - 0.3:
                    if self.awaiting_result:
                        return BotIntent()
                    self.awaiting_result = True
                    return BotIntent(interact_target=f"body_{who}")
                return self._go_point(obs, *pos)
            if who in obs.visible_positions:
                return self._go_point(obs, *obs.visible_positions[who])
            self.point_goal = None
        if self.goal is not None and self.goal.kind == "beacon" and obs.beacons.get(self.goal.target_id):
            self.goal = None  # someone else lit it first
        return self._navigate(obs)

    def on_interact_result(self, ok: bool, reason: str, tick: int) -> None:
        if self.goal is not None and self.goal.kind == "beacon":
            if ok and not self.is_islander():
                self.faked.add(self.goal.target_id)
            if ok or reason == "already_lit":
                self.beacon_errand = False
        if self.point_goal is not None and self.point_goal[0] == "report":
            self.point_goal = None
        super().on_interact_result(ok, reason, tick)

    # ------------------------------------------------------------- main
    def update(self, obs: Observation) -> BotIntent:
        self._observe(obs)
        for ev in obs.new_events:
            self._learn_event(obs, ev)
        if not obs.match_running or not obs.alive:
            return BotIntent()
        actions = self._social_island(obs)
        if obs.phase != "explore":
            self.goal = None
            self.point_goal = None
            self.path = []
            self.awaiting_result = False
            return BotIntent(actions=tuple(actions))
        if self.role == R.IMPOSTOR:
            kill = self._hunt(obs)
            if kill is not None:
                return BotIntent(actions=(*actions, kill))
        if self.role == R.SHERIFF and not obs.bullet_used:
            shot = self._sheriff(obs)
            if shot is not None:
                return BotIntent(actions=(*actions, shot))
        move = self._navigate_island(obs)
        return BotIntent(move.dx, move.dy, move.interact_target, tuple(actions))
