"""Agent Lab payloads: interaction graph, timeline, decisions, replay data and metrics.

Visibility rule: while a match is running, the Lab shows only public information (no private
events, objectives, agent contexts or decisions), so it can't be used to cheat. After the match
ends, the full record is revealed for analysis. Agent *explanations* are clearly marked as
generated; facts come only from the event log.
"""

from __future__ import annotations

from typing import Any

from .agents.coordinator import AgentCoordinator
from .engine.events import GameEvent
from .engine.match import Match

EDGE_TYPES = (
    "message",
    "alliance_proposed",
    "alliance_formed",
    "alliance_rejected",
    "alliance_broken",
    "vote",
    "shrine",
)


def build_graph(events: list[dict[str, Any]]) -> dict[str, Any]:
    """Aggregate interactions into weighted directed edges."""
    edges: dict[tuple[str, str, str], dict[str, Any]] = {}

    def bump(kind: str, a: str, b: str, seq: int) -> None:
        if not a or not b or a == b:
            return
        key = (kind, a, b)
        e = edges.setdefault(key, {"type": kind, "source": a, "target": b, "count": 0, "seqs": []})
        e["count"] += 1
        e["seqs"].append(seq)

    for ev in events:
        d, t, seq = ev["data"], ev["type"], ev["seq"]
        if t == "chat" and d.get("to"):
            bump("message", d["sender"], d["to"], seq)
        elif t == "alliance_proposed":
            bump("alliance_proposed", d["proposer"], d["target"], seq)
        elif t == "alliance_formed":
            a, b = d["members"]
            bump("alliance_formed", a, b, seq)
        elif t == "alliance_rejected":
            bump("alliance_rejected", d["target"], d["proposer"], seq)
        elif t == "alliance_broken":
            bump("alliance_broken", d["by"], d["partner"], seq)
        elif t == "vote_resolved":
            for voter, target in d["votes"].items():
                if target != "skip":
                    bump("vote", voter, target, seq)
        elif t == "shrine_activated":
            ps = d["participants"]
            for i, a in enumerate(ps):
                for b in ps[i + 1 :]:
                    bump("shrine", a, b, seq)
    return {"edge_types": list(EDGE_TYPES), "edges": list(edges.values())}


def _phase_of(events: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Annotate each event with the phase id it happened in (for timeline filters)."""
    phase, meeting = "explore", 0
    trans = {"meeting_called": "discuss", "vote_started": "vote", "vote_resolved": "reveal", "meeting_ended": "explore"}
    out = []
    for ev in events:
        if ev["type"] == "meeting_called":
            meeting = int(ev["data"]["meeting"])
        if ev["type"] in trans:
            phase = trans[ev["type"]]
        out.append({**ev, "phase_id": f"{meeting}:{phase}"})
    return out


def event_dict(e: GameEvent) -> dict[str, Any]:
    d = e.to_dict()
    if e.visible_to is not None:
        d["visible_to"] = sorted(e.visible_to)
    return d


def payload_from_live(match: Match, coordinator: AgentCoordinator | None, room_code: str | None) -> dict[str, Any]:
    finished = match.status == "finished"
    events = [event_dict(e) for e in match.events if finished or e.visible_to is None]
    contestants = [
        {**c.roster_dict(), "objective": c.objective.to_dict(match.names()) if finished and c.objective else None}
        for c in match.contestants.values()
    ]
    return assemble(
        match_id=match.id,
        room_code=room_code,
        status=match.status,
        map_id=match.map.id,
        seed=match.seed,
        ticks=match.tick,
        contestants=contestants,
        events=events,
        decisions=[r.to_dict() for r in coordinator.records] if (coordinator and finished) else [],
        agent_summary=coordinator.summary() if coordinator else None,
        result=match.result,
    )


def assemble(**kw: Any) -> dict[str, Any]:
    events = _phase_of(kw.pop("events"))
    finished = kw["status"] == "finished"
    return {
        **kw,
        "full_record": finished,
        "visibility_note": None
        if finished
        else "Match in progress: only public information is shown. The full record opens when it ends.",
        "events": events,
        "graph": build_graph(events),
        "decisions_note": "Decision summaries are generated by the agent's strategist (model or planner) and are "
        "explanations, not facts. Facts come only from the event log.",
    }


def redact_private_human_chat(payload: dict[str, Any]) -> dict[str, Any]:
    """Hide the text of private messages (whispers, ghost chat) that involve a human player.

    The Lab is public; players expect their private conversations to stay private. Bot-only
    threads stay readable (they are the research subject). Admins see everything.
    """
    humans = {c["id"] for c in payload.get("contestants", []) if not c.get("is_bot")}
    for ev in payload.get("events", []):
        if ev.get("type") != "chat" or "visible_to" not in ev:
            continue
        involved = {ev["data"].get("sender"), *ev["visible_to"]}
        if involved & humans:
            ev["data"] = {**ev["data"], "text": "[private message hidden]", "payload": {}}
    payload["privacy_note"] = "Private messages that involve human players are hidden."
    return payload
